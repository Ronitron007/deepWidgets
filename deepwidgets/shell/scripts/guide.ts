/**
 * Write the OpenUI guide of the component set `shadcn-widgets@1` to `dist/guide.md`
 * (`widget_phase2.creation.tools`). The MCP tool `widget_guide` serves this file, so the guide
 * always matches the components that the shell renders.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CATALOG_ID, widgetLibrary } from '../src/library.tsx'

const out = join(import.meta.dirname, '..', 'dist', 'guide.md')
const text = widgetLibrary.prompt({ toolCalls: true, bindings: true })
mkdirSync(join(out, '..'), { recursive: true })
writeFileSync(out, `<!-- component set ${CATALOG_ID}; generated by deepwidgets/shell/scripts/guide.ts -->\n${text}\n`)
console.log(`guide: wrote ${out} (${String(text.length)} characters)`)
