/**
 * Write the OpenUI guide of the component set `shadcn-widgets@1` to `dist/guide.md`
 * (`widget_phase2.creation.tools`). The MCP tool `widget_guide` serves this file, so the guide
 * always matches the components that the shell renders.
 *
 * The prompt of lang-core is written for a chat reply. The guide replaces its preamble and removes
 * the steps `@ToAssistant` and `@OpenUrl`, because the shell only records them. The build fails
 * when lang-core changes the text that the edits find.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CATALOG_ID, widgetLibrary } from '../src/library.tsx'

const PREAMBLE = 'This guide describes OpenUI Lang, the language of the `program` text of a widget. The shell renders the program in the widget window. Write the program as one string in the widget code.'

const RULES = [
  'In a widget, Query("name", args, defaults) calls the widget action `name` of kind query, and Mutation("name", args) calls the action `name` of kind mutation. The tool name is the action name.',
  'In a widget, the steps @Run, @Set, and @Reset work. A button without an action does nothing.',
]

/** The edits: each `find` must occur in the lang-core text. */
const EDITS: { find: string | RegExp, replace: string }[] = [
  { find: ', @ToAssistant, @OpenUrl', replace: '' },
  {
    find: /Pass one @-prefixed step bare, e\.g\. Button\("Ask", @ToAssistant\("Tell me more"\)\)\. Put several steps in Action\(\[\.\.\.\]\), e\.g\. Button\("Read", Action\(\[@OpenUrl\("https:\/\/example\.com"\), @ToAssistant\("Summarize this page"\)\]\)\)\. Steps execute in order\.\nButtons without an action automatically send their label to the assistant \(equivalent to @ToAssistant\(label\)\)\./,
    replace: 'Pass one @-prefixed step bare, e.g. Button("Add", @Run(add)). Put several steps in Action([...]), e.g. Button("Add", Action([@Run(add), @Run(s)])). Steps execute in order.',
  },
  { find: /^- @ToAssistant\(.*\n/m, replace: '' },
  { find: /^- @OpenUrl\(.*\n/m, replace: '' },
  { find: /\n\nExample — simple nav:\n```\n.*@OpenUrl.*\n```/, replace: '' },
]

let text = widgetLibrary.prompt({ toolCalls: true, bindings: true, preamble: PREAMBLE, additionalRules: RULES })
for (const { find, replace } of EDITS) {
  const found = typeof find === 'string' ? text.includes(find) : find.test(text)
  if (!found) throw new Error(`guide: the lang-core prompt has no ${String(find)}; update scripts/guide.ts`)
  text = text.replace(find, replace)
}
const left = /@ToAssistant|@OpenUrl|ENTIRE response/.exec(text)
if (left !== null) throw new Error(`guide: the text still has ${left[0]}; update scripts/guide.ts`)

const out = join(import.meta.dirname, '..', 'dist', 'guide.md')
mkdirSync(join(out, '..'), { recursive: true })
writeFileSync(out, `<!-- component set ${CATALOG_ID}; generated by deepwidgets/shell/scripts/guide.ts -->\n${text}\n`)
console.log(`guide: wrote ${out} (${String(text.length)} characters)`)
